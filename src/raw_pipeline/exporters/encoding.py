"""Pixel encoding shared by exporters, report thumbnails and previews.

This is the only place (with :mod:`raw_pipeline.core.color`) where scene-linear
working-space pixels become display-referred sRGB values. Resizing happens in
linear light, before the transfer function, so averages are physically correct.
"""

from __future__ import annotations

import functools
from typing import Final

import cv2
import numpy as np
from numpy.typing import NDArray
from PIL import ImageCms

from raw_pipeline.core.color import srgb_encode, to_uint8, to_uint16
from raw_pipeline.core.geometry import PreviewGeometry

ICC_DATE_OFFSET: Final = 24
"""Byte offset of the creation ``dateTimeNumber`` in an ICC profile header."""

ICC_DATE_LENGTH: Final = 12
"""Length in bytes of the ICC ``dateTimeNumber`` (six big-endian uint16)."""

ICC_FIXED_DATE: Final = (2026, 1, 1, 0, 0, 0)
"""Creation date written into the generated profile so its bytes never change."""


def output_size(width: int, height: int, long_edge_px: int | None) -> tuple[int, int]:
    """Return ``(width, height)`` after fitting the long edge to ``long_edge_px``.

    Images are never upscaled; ``None`` keeps the full size.
    """
    if long_edge_px is None:
        return width, height
    geometry = PreviewGeometry.for_long_edge(width, height, long_edge_px)
    return geometry.preview_width, geometry.preview_height


def resize_long_edge(image: NDArray[np.float32], long_edge_px: int | None) -> NDArray[np.float32]:
    """Downscale a scene-linear ``(H, W, 3)`` image with an area filter.

    Args:
        image: Scene-linear float32 image; values above 1.0 are preserved.
        long_edge_px: Target long edge in pixels; ``None`` or a larger value
            returns the input unchanged (no copy, never upscaled).

    Returns:
        float32 ``(h, w, 3)`` image, still scene-linear.
    """
    height, width = image.shape[:2]
    size = output_size(width, height, long_edge_px)
    if size == (width, height):
        return image
    resized = cv2.resize(np.ascontiguousarray(image), size, interpolation=cv2.INTER_AREA)
    return np.asarray(resized, dtype=np.float32)


def encode_srgb_uint8(image: NDArray[np.float32]) -> NDArray[np.uint8]:
    """Clip a scene-linear image to [0, 1], apply the sRGB transfer function and quantize to 8 bits."""
    return to_uint8(srgb_encode(image))


def encode_srgb_uint16(image: NDArray[np.float32]) -> NDArray[np.uint16]:
    """Clip a scene-linear image to [0, 1], apply the sRGB transfer function and quantize to 16 bits."""
    return to_uint16(srgb_encode(image))


def srgb_thumbnail(image: NDArray[np.float32], long_edge_px: int | None) -> NDArray[np.uint8]:
    """Downscale (linear light) then sRGB-encode a scene-linear image to display-ready uint8."""
    return encode_srgb_uint8(resize_long_edge(image, long_edge_px))


@functools.cache
def srgb_icc_profile() -> bytes:
    """Return the sRGB ICC profile embedded in every output.

    The profile is generated by LittleCMS through Pillow. LittleCMS stamps the
    current time into the header, so the date is replaced by
    :data:`ICC_FIXED_DATE` to keep outputs byte-identical across runs (the
    profile ID field is left zero, i.e. "not computed", as LittleCMS writes it).
    """
    profile = bytearray(ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes())
    date = b"".join(part.to_bytes(2, "big") for part in ICC_FIXED_DATE)
    profile[ICC_DATE_OFFSET : ICC_DATE_OFFSET + ICC_DATE_LENGTH] = date
    return bytes(profile)
